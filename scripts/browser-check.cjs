/* Run with a locally available Playwright package; no runtime dependency. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 2 });
  const page = await context.newPage();
  const errors = [], resources = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(`${message.text()} ${JSON.stringify(message.location())}`); });
  page.on('response', response => { resources.push(response.url()); if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  await page.goto(process.env.ATLAS_URL || 'http://127.0.0.1:5174/');
  await page.waitForSelector('#scene[data-vector-regions]');
  await page.waitForTimeout(900);
  if (await page.locator('html').getAttribute('data-theme') === 'dark') await page.locator('#theme-toggle').click();
  await page.screenshot({ path: '/private/tmp/vector-atlas-desktop.png' });
  const stats = await page.locator('#scene').evaluate(el => ({ ...el.dataset, width: el.width, height: el.height }));
  await page.locator('#node-rail button').nth(2).click();
  await page.waitForTimeout(900);
  const selectedName = await page.locator('#node-rail button small').nth(2).textContent();
  if (!await page.locator('#city-panel').textContent().then(t => t.includes(selectedName))) throw new Error('Node selection failed');
  for (let i=0; i<12; i++) await page.locator('#zoom-in').click();
  await page.waitForTimeout(1200);
  const maxZoom = await page.locator('#viewport-status').textContent();
  await page.screenshot({ path: '/private/tmp/vector-atlas-zoom.png' });
  await page.locator('#theme-toggle').click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: '/private/tmp/vector-atlas-dark.png' });
  await page.locator('#reset-view').click();
  await page.waitForTimeout(900);
  const before = await page.locator('#viewport-status').textContent();
  await page.mouse.move(720,450);
  await page.mouse.wheel(0,400);
  await page.waitForTimeout(900);
  const after = await page.locator('#viewport-status').textContent();
  if (before === after) throw new Error('Wheel did not rotate map');
  await page.locator('#author-toggle').click();
  await page.mouse.click(700,420);
  await page.waitForSelector('#author-snippet.show');
  const snippet = await page.locator('#author-code').textContent();
  if (!snippet.includes('x:') || !snippet.includes('y:')) throw new Error('Coordinate editor failed');
  await page.locator('#author-toggle').click();
  await page.locator('#theme-toggle').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#reset-view').click();
  await page.waitForTimeout(900);
  await page.screenshot({ path: '/private/tmp/vector-atlas-mobile.png' });
  const mobile = await page.evaluate(() => ({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:innerHeight,scrollHeight:document.documentElement.scrollHeight}));
  if(mobile.scrollWidth>mobile.width || mobile.scrollHeight>mobile.height) throw new Error('Mobile viewport overflow');
  await page.locator('#theme-toggle').click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: '/private/tmp/vector-atlas-mobile-dark.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload();
  await page.waitForSelector('#scene[data-vector-regions]');
  const reducedMotion = await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches);
  const result = { stats, maxZoom, wheelChangedAzimuth: before !== after, editor: snippet, mobile, reducedMotion, rasterAtlasRequested: resources.some(url => url.includes('fantasy-world-map.jpg')), errors };
  const reviewUrl = new URL('vector-review.html', process.env.ATLAS_URL || 'http://127.0.0.1:5174/').href;
  await page.goto(reviewUrl);
  await page.waitForSelector('#vector svg');
  result.reviewRegionCount = await page.locator('#vector path[id]').count();
  await page.locator('#only-vector').click();
  await page.locator('#zoom').selectOption('4');
  result.review400PercentWidth = await page.locator('#map').evaluate(el => el.getBoundingClientRect().width);
  if (result.reviewRegionCount !== Number(stats.vectorRegions) || result.review400PercentWidth !== 36864) throw new Error('Vector review page failed');
  await page.setViewportSize({width:1440,height:960});
  await page.goto(new URL('?view=seam',process.env.ATLAS_URL || 'http://127.0.0.1:5174/').href);
  await page.waitForSelector('#scene[data-vector-regions]');
  if(await page.locator('html').getAttribute('data-theme')==='dark')await page.locator('#theme-toggle').click();
  await page.waitForTimeout(500);
  await page.screenshot({path:'/private/tmp/vector-atlas-seam.png'});
  await page.locator('#theme-toggle').click();
  await page.waitForTimeout(500);
  await page.screenshot({path:'/private/tmp/vector-atlas-seam-dark.png'});
  console.log(JSON.stringify(result,null,2));
  await fs.writeFile('/private/tmp/vector-atlas-browser-check.json',JSON.stringify(result,null,2));
  await browser.close();
  if (errors.length || result.rasterAtlasRequested) process.exitCode=1;
})().catch(error => { console.error(error); process.exit(1); });
